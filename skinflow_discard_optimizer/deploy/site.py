"""Per-press site configuration.

``site/site.yaml`` names the press and its OPC-UA namespace; ``render_contract`` rewrites the shipped
``contracts/signals.yaml`` to match and validates the result with the normal contract schema, so a
bad tag fails at configure time instead of on the first live cycle.

This module must stay importable *before* ``skinflow_discard_optimizer.paths``: ``apply_site_env``
sets ``SKDO_SIGNALS_YAML``, which ``paths`` reads once at import.
"""
from __future__ import annotations

import os
import re
from dataclasses import dataclass, field
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SHIPPED_CONTRACT = ROOT / "contracts" / "signals.yaml"
SITE_DIR = Path(os.environ.get("SKDO_SITE_DIR") or ROOT / "site")
SITE_FILE = SITE_DIR / "site.yaml"
SITE_CONTRACT = SITE_DIR / "signals.yaml"

_ID = re.compile(r"^[A-Za-z0-9_]+$")
_TAG_ID = re.compile(r"^[A-Za-z0-9_.]+$")


@dataclass(frozen=True)
class SiteConfig:
    press_id: str = "Press01"
    namespace_index: int = 2
    opcua_endpoint: str = ""
    # signal name (as in contracts/signals.yaml) -> string identifier after ``ns=<n>;s=``
    tag_overrides: dict[str, str] = field(default_factory=dict)

    def validate(self) -> None:
        if not _ID.match(self.press_id):
            raise ValueError(f"press_id must be alphanumeric/underscore, got {self.press_id!r}")
        if not 0 <= self.namespace_index < 65536:
            raise ValueError(f"namespace_index out of range: {self.namespace_index}")
        for name, ident in self.tag_overrides.items():
            if not _TAG_ID.match(ident):
                raise ValueError(f"tag_overrides[{name}]={ident!r}: only letters, digits, '_' and '.' are allowed")

    @classmethod
    def load(cls, path: Path = SITE_FILE) -> "SiteConfig":
        raw = yaml.safe_load(path.read_text(encoding="utf-8")) if path.exists() else {}
        unknown = set(raw or {}) - set(cls.__dataclass_fields__)
        if unknown:
            raise ValueError(f"{path}: unknown keys {sorted(unknown)}")
        cfg = cls(**(raw or {}))
        cfg.validate()
        return cfg

    def save(self, path: Path = SITE_FILE) -> None:
        self.validate()
        path.parent.mkdir(parents=True, exist_ok=True)
        data = {k: getattr(self, k) for k in self.__dataclass_fields__}
        path.write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")


def render_contract(site: SiteConfig, src: Path = SHIPPED_CONTRACT) -> dict:
    """Shipped contract with the press id, namespace index and per-signal overrides applied."""
    from skinflow_discard_optimizer.contracts.schema import SignalContract

    doc = yaml.safe_load(src.read_text(encoding="utf-8"))
    shipped_ns = doc["namespace_index"]
    unknown = set(site.tag_overrides) - set(doc["signals"])
    if unknown:
        raise ValueError(f"tag_overrides names unknown input signals {sorted(unknown)} "
                         "(Predictor.* outputs are fixed and cannot be overridden)")

    def retag(tag: str) -> str:
        return tag.replace(f"ns={shipped_ns};", f"ns={site.namespace_index};", 1).replace(
            ";s=Press01.", f";s={site.press_id}.")

    for name, spec in doc["signals"].items():
        spec["tag"] = retag(spec["tag"])
        if name in site.tag_overrides:
            spec["tag"] = f"ns={site.namespace_index};s={site.tag_overrides[name]}"
    for spec in doc["outputs"]["signals"].values():
        spec["tag"] = retag(spec["tag"])
    doc["namespace_index"] = site.namespace_index
    SignalContract.model_validate(doc)  # raises on duplicates, wrong namespace, setpoint-like outputs, ...
    return doc


def write_site_contract(site: SiteConfig, dest: Path = SITE_CONTRACT) -> Path:
    doc = render_contract(site)
    dest.parent.mkdir(parents=True, exist_ok=True)
    header = "# GENERATED by `skdo configure` from contracts/signals.yaml + site/site.yaml. Do not edit.\n"
    dest.write_text(header + yaml.safe_dump(doc, sort_keys=False), encoding="utf-8")
    return dest


def apply_site_env() -> Path | None:
    """If a site contract has been generated, point the package at it. Call before importing ``paths``."""
    if os.environ.get("SKDO_SIGNALS_YAML"):
        return Path(os.environ["SKDO_SIGNALS_YAML"])
    if SITE_CONTRACT.exists():
        os.environ["SKDO_SIGNALS_YAML"] = str(SITE_CONTRACT)
        return SITE_CONTRACT
    return None
